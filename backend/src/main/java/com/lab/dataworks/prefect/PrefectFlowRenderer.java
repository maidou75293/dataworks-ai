    public RenderedFlow render(long workflowId, String projectCode, String workflowCode, String workflowName,
                               String env, String modelJson, String cron, int versionNo,
                               String deploymentName) {
        JsonNode model;
        try {
            model = mapper.readTree(modelJson == null || modelJson.isBlank() ? "{}" : modelJson);
        } catch (Exception e) {
            throw ApiException.badRequest("工作流模型不是合法 JSON: " + e.getMessage());
        }
        JsonNode tasks = model.path("tasks");
        JsonNode edges = model.path("edges");
        if (!tasks.isArray() || tasks.isEmpty()) {
            throw ApiException.badRequest("工作流至少需要一个任务");
        }

        Map<String, JsonNode> taskByCode = new LinkedHashMap<>();
        for (JsonNode task : tasks) {
            String code = task.path("code").asText("");
            if (!code.matches("[A-Za-z_][A-Za-z0-9_]{0,63}")) {
                throw ApiException.badRequest("任务编码不合法（字母开头，只含字母数字下划线）: " + code);
            }
            if (taskByCode.putIfAbsent(code, task) != null) {
                throw ApiException.badRequest("任务编码重复: " + code);
            }
            String type = task.path("type").asText("SQL").toUpperCase(Locale.ROOT);
            if (!Set.of("SQL", "SHELL", "PYTHON", "QUALITY_GATE").contains(type)) {
                throw ApiException.badRequest("不支持的任务类型: " + type);
            }
            if (type.equals("QUALITY_GATE") && task.path("ruleCode").asText("").isBlank()) {
                throw ApiException.badRequest("质量闸门任务必须指定规则编码: " + code);
            }
        }
        Map<String, List<String>> next = new LinkedHashMap<>();
        Map<String, Integer> indegree = new LinkedHashMap<>();
        Map<String, List<String>> deps = new LinkedHashMap<>();
        taskByCode.keySet().forEach(c -> {
            indegree.put(c, 0);
            next.put(c, new ArrayList<>());
            deps.put(c, new ArrayList<>());
        });
        for (JsonNode edge : edges) {
            String from = edge.path("from").asText("");
            String to = edge.path("to").asText("");
            if (!taskByCode.containsKey(from) || !taskByCode.containsKey(to)) {
                throw ApiException.badRequest("依赖引用了不存在的任务: " + from + " -> " + to);
            }
            if (from.equals(to)) {
                throw ApiException.badRequest("任务不能依赖自己: " + from);
            }
            next.get(from).add(to);
            deps.get(to).add(from);
            indegree.merge(to, 1, Integer::sum);
        }
        List<String> order = topologicalOrder(taskByCode.keySet(), next, indegree);

        String flowName = flowName(projectCode, env, workflowCode);
        // 工作流编码只在项目内唯一，但 ConfigMap 是全局的：filename 必须带
        // workflowId，否则两个项目下的同名工作流会互相覆盖 Flow 文件。
        String functionName = "flow_" + workflowCode + "_" + workflowId;
        String filename = "wf" + workflowId + "_" + deploymentName + ".py";
        String entrypoint = "/opt/prefect/flows/" + filename + ":" + functionName;

        StringBuilder py = new StringBuilder();
        py.append("# generated by dataworks-platform; do not edit by hand\n");
        py.append("# workflow=").append(workflowCode).append(" env=").append(env)
                .append(" v").append(versionNo).append("\n");
        py.append("from __future__ import annotations\n\n");
        py.append("import base64\n");
        py.append("import os\n");
        py.append("import re\n");
        py.append("import subprocess\n\n");
        py.append("from prefect import flow, task\n");
        py.append("from prefect.logging import get_run_logger\n\n");
        py.append("""
                def _log(message):
                    # v450 P1-5：裸 print 不进 Prefect 任务日志，统一走 get_run_logger
                    try:
                        get_run_logger().info(message)
                    except Exception:
                        print(message)

                """);
        py.append("FLOW_NAME = ").append(pyStr(flowName)).append("\n");
        py.append("WORKFLOW_ID = ").append(workflowId).append("\n");
        py.append("WORKFLOW_VERSION = ").append(versionNo).append("\n");
        py.append("WORKFLOW_ENV = ").append(pyStr(env)).append("\n\n");

        py.append("""
                def _connect():
                    import psycopg2
                    return psycopg2.connect(
                        host=os.environ["DW_DB_HOST"],
                        port=int(os.environ.get("DW_DB_PORT", "5432")),
                        dbname=os.environ["DW_DB_NAME"],
                        user=os.environ["DW_DB_USER"],
                        password=os.environ["DW_DB_PASSWORD"],
                        connect_timeout=10,
                    )

                def _connect_doris():
                    import pymysql
                    return pymysql.connect(
                        host=os.environ["DORIS_HOST"],
                        port=int(os.environ.get("DORIS_PORT", "9030")),
                        user=os.environ["DORIS_USER"],
                        password=os.environ["DORIS_PASSWORD"],
                        charset="utf8mb4",
                        connect_timeout=10,
                    )

                def _parse_jdbc(url):
                    # jdbc:postgresql://host:5432/db?x  /  jdbc:mysql://host:9030/db
                    m = re.match(r"jdbc:[^:]+://([^/:?;]+)(?::(\\d+))?(?:/([^?;]+))?", url or "")
                    if not m:
                        raise RuntimeError(f"无法解析 JDBC URL: {url}")
                    return m.group(1), m.group(2), m.group(3) or ""

                def _datasource(ds_id):
                    # 平台库里数据源密码是 AES-GCM 密文，运行时通过内部接口取明文
                    import json as _json
                    import urllib.request as _urllib
                    base = os.environ.get(
                        "BACKEND_URL",
                        "http://dataworks-backend.dw-dev.svc.cluster.local:8080").rstrip("/")
                    req = _urllib.Request(
                        f"{base}/api/internal/datasources/{int(ds_id)}",
                        headers={"X-Internal-Token": os.environ.get("PLATFORM_INTERNAL_TOKEN", "")},
                    )
                    with _urllib.urlopen(req, timeout=10) as resp:
                        data = _json.loads(resp.read().decode("utf-8"))
                    return data["name"], data["dsType"], data["jdbcUrl"], data["username"], data["password"]

                def _connect_ds(ds_id):
                    if ds_id is None:
                        return None
                    name, ds_type, url, username, password = _datasource(ds_id)
                    host, port, dbname = _parse_jdbc(url)
                    if (ds_type or "").upper() == "POSTGRESQL":
                        import psycopg2
                        return psycopg2.connect(
                            host=host, port=int(port or 5432), dbname=dbname,
                            user=username, password=password, connect_timeout=10)
                    import pymysql
                    return pymysql.connect(
                        host=host, port=int(port or 3306), database=dbname,
                        user=username, password=password, charset="utf8mb4",
                        connect_timeout=10)

                def _record_lineage(task_code, sql):
                    # 运行期血缘：失败只打印，绝不阻断任务；网络抖动重试 3 次
                    import json as _json
                    import time as _time
                    import urllib.request as _urllib
                    try:
                        from prefect.runtime import flow_run as _flow_run
                        run_id = _flow_run.id or ""
                    except Exception:
                        run_id = os.environ.get("PREFECT__FLOW_RUN_ID", "")
                    base = os.environ.get(
                        "BACKEND_URL",
                        "http://dataworks-backend.dw-dev.svc.cluster.local:8080").rstrip("/")
                    payload = _json.dumps({
                        "workflowId": WORKFLOW_ID,
                        "versionNo": WORKFLOW_VERSION,
                        "env": WORKFLOW_ENV,
                        "taskCode": task_code,
                        "sql": sql,
                        "runId": run_id,
                    }).encode("utf-8")
                    last = None
                    for _attempt in range(3):
                        try:
                            req = _urllib.Request(
                                base + "/api/internal/lineage/runtime", data=payload, method="POST",
                                headers={"Content-Type": "application/json",
                                         "X-Internal-Token": os.environ.get("PLATFORM_INTERNAL_TOKEN", "")})
                            with _urllib.urlopen(req, timeout=3) as resp:
                                resp.read()
                            return
                        except Exception as e:
                            last = e
                            _time.sleep(0.5 * (_attempt + 1))
                    print("lineage record skipped:", last)

                def _check_quality_blocks(biz_date):
                    # TC7-G2：上游表的强规则当天没通过，下游工作流本次不调度。
                    # 定时调度由 Prefect 直接建 run，不经过后端触发口，所以必须在 Flow
                    # 里再问一次。判定逻辑只在后端一份（反查下游要算血缘传递闭包），
                    # 这里只负责把结论变成明确失败，不能静默跳过。
                    import json as _json
                    import urllib.request as _urllib
                    base = os.environ.get(
                        "BACKEND_URL",
                        "http://dataworks-backend.dw-dev.svc.cluster.local:8080").rstrip("/")
                    payload = _json.dumps({
                        "workflowId": WORKFLOW_ID,
                        "env": WORKFLOW_ENV,
                        "bizDate": biz_date,
                    }).encode("utf-8")
                    req = _urllib.Request(
                        base + "/api/internal/quality/blockers", data=payload, method="POST",
                        headers={"Content-Type": "application/json",
                                 "X-Internal-Token": os.environ.get("PLATFORM_INTERNAL_TOKEN", "")})
                    with _urllib.urlopen(req, timeout=10) as resp:
                        data = _json.loads(resp.read().decode("utf-8"))
                    if data.get("blocked"):
                        reasons = "；".join(
                            b.get("message") or b.get("ruleCode", "?")
                            for b in (data.get("blockers") or []))
                        raise RuntimeError(
                            "上游强规则未通过，下游任务不调度（TC7-G2）：" + reasons)

                def _run_sql(code_b64, biz_date, datasource="DORIS", datasource_id=None, task_code="", database=""):
                    import time as _time
                    sql = base64.b64decode(code_b64).decode("utf-8").replace("${biz_date}", biz_date)
                    # v450 P1-5：成功也要留痕——SQL 摘要、影响行数、耗时、涉及表。
                    summary = " ".join(sql.split())
                    if len(summary) > 500:
                        summary = summary[:500] + "…"
                    _log(f"[{task_code}] SQL({datasource}{'' if datasource_id is None else '/' + str(datasource_id)}): {summary}")
                    started = _time.time()
                    if datasource_id is not None:
                        conn = _connect_ds(datasource_id)
                    else:
                        conn = _connect_doris() if datasource == "DORIS" else _connect()
                    try:
                        with conn:
                            with conn.cursor() as cur:
                                # v450：节点可以绑定默认库；SQL 里就能只写表名
                                if database:
                                    if datasource == "PG" and datasource_id is None:
                                        cur.execute("SET search_path TO " + database)
                                    else:
                                        cur.execute("USE `" + database.replace("`", "") + "`")
                                cur.execute(sql)
                                if cur.description:
                                    rows = cur.fetchall()
                                    _log(f"[{task_code}] rows={len(rows)} elapsed={( _time.time() - started):.2f}s first={rows[:5]}")
                                else:
                                    _log(f"[{task_code}] rowcount={cur.rowcount} elapsed={(_time.time() - started):.2f}s")
                    except Exception as exc:
                        message = str(exc)
                        if "Current database is not set" in message:
                            raise RuntimeError(
                                "项目未配置默认库：请在 SQL 中使用 <库>.<表>，或为项目设置默认库") from exc
                        raise
                    finally:
                        # pymysql 的 Connection.__exit__ 已经 close，重复 close 会抛
                        # Error('Already closed')，所以这里必须容忍。
                        try:
                            conn.close()
                        except Exception:
                            pass
                    _record_lineage(task_code, sql)

                def _run_shell(code_b64, biz_date):
                    script = base64.b64decode(code_b64).decode("utf-8").replace("${biz_date}", biz_date)
                    print("SHELL:", script)
                    subprocess.run(script, shell=True, check=True, executable="/bin/bash")

                def _run_python(code_b64, biz_date):
                    script = base64.b64decode(code_b64).decode("utf-8").replace("${biz_date}", biz_date)
                    print("PYTHON:", script)
                    exec(compile(script, "<platform-task>", "exec"), {"__name__": "__main__", "biz_date": biz_date})

                def _mask_sql(sql, backslash):
                    # 只掩掉单引号字符串；两种转义解释都要检查（与后端 guardReadOnly 同口径）
                    out = []
                    i = 0
                    quote = False
                    while i < len(sql):
                        ch = sql[i]
                        if not quote:
                            if ch == "'":
                                quote = True
                                out.append(" ")
                            else:
                                out.append(ch)
                            i += 1
                            continue
                        if backslash and ch == "\\\\":
                            out.append(" ")
                            i += 2
                            continue
                        if ch == "'":
                            if i + 1 < len(sql) and sql[i + 1] == "'":
                                i += 2
                            else:
                                quote = False
                                i += 1
                            out.append(" ")
                            continue
                        out.append(" ")
                        i += 1
                    return "".join(out)

                _QUALITY_BANNED = ("insert", "update", "delete", "drop", "alter", "create",
                                   "truncate", "grant", "revoke", "merge", "copy", "call",
                                   "vacuum", "replace", "outfile", "dumpfile")

                def _guard_readonly(sql):
                    # 质量规则执行的是用户写的 SQL，由 Flow 用平台/数据源账号跑：
                    # 这里必须和后端一样只放行单条 SELECT/WITH，否则有 quality:write
                    # 的人可以借工作流执行 DELETE/DDL。
                    if "/*!" in sql:
                        raise RuntimeError("质量规则 SQL 不允许执行型注释 /*! */")
                    for backslash in (True, False):
                        text = _mask_sql(sql, backslash)
                        text = re.sub(r"/\\*.*?\\*/", " ", text, flags=re.S)
                        text = re.sub(r"--[^\\n]*", " ", text)
                        code = text.strip()
                        while code.endswith(";"):
                            code = code[:-1].strip()
                        if ";" in code:
                            raise RuntimeError("质量规则只允许单条只读查询")
                        low = code.lower()
                        if not (low.startswith("select") or low.startswith("with")):
                            raise RuntimeError("质量规则只允许 SELECT / WITH")
                        for word in _QUALITY_BANNED:
                            if re.search(r"(^|[^a-z0-9_])" + word + r"([^a-z0-9_]|$)", low):
                                raise RuntimeError("质量规则不允许包含 " + word.upper())
                        if re.search(r"\\bfor\\s+update\\b", low):
                            raise RuntimeError("质量规则不允许 FOR UPDATE")
                    return sql

                def _mcp_sql(sql, max_rows=1):
                    import json as _json
                    import urllib.request as _urllib
                    url = os.environ["MCP_URL"].rstrip("/") + "/tools/doris.sql_query"
                    payload = _json.dumps({"params": {"sql": sql, "max_rows": max_rows}}).encode()
                    req = _urllib.Request(
                        url, data=payload, method="POST",
                        headers={"Content-Type": "application/json",
                                 "Authorization": "Bearer " + os.environ.get("MCP_TOKEN", "")})
                    with _urllib.urlopen(req, timeout=60) as resp:
                        data = _json.loads(resp.read().decode())
                    rows = data.get("result", {}).get("rows") or []
                    return rows[0][0] if rows else None

                def _run_quality_gate(rule_code, biz_date):
                    conn = _connect()
                    ds_conn = None
                    try:
                        with conn:
                            with conn.cursor() as cur:
                                # 规则编码只在项目内唯一：按当前工作流所属项目取，
                                # 否则别的项目同名规则会被误用
                                cur.execute(
                                    "select id, rule_type, table_name, column_name, config_json, "
                                    "datasource, datasource_id "
                                    "from platform.quality_rule where code=%s and enabled "
                                    "and project_id = (select project_id from platform.workflow "
                                    "where id=%s) order by id limit 1", (rule_code, WORKFLOW_ID))
                                row = cur.fetchone()
                                if not row:
                                    raise RuntimeError(f"quality rule not found: {rule_code}")
                                (rule_id, rule_type, table_name, column_name, config,
                                 datasource, datasource_id) = row
                                config = config or {}
                                datasource = (datasource or "PG").upper()
                                ds_conn = _connect_ds(datasource_id)
                                if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_.]*", table_name):
                                    raise RuntimeError("invalid table name")
                                if column_name and not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", column_name):
                                    raise RuntimeError("invalid column name")

                                def scalar(sql):
                                    if ds_conn is not None:
                                        with ds_conn.cursor() as ds_cur:
                                            ds_cur.execute(sql)
                                            value = ds_cur.fetchone()[0]
                                            return float(value) if value is not None else 0.0
                                    if datasource == "DORIS":
                                        value = _mcp_sql(sql)
                                        return float(value) if value is not None else 0.0
                                    cur.execute(sql)
                                    value = cur.fetchone()[0]
                                    return float(value) if value is not None else 0.0

                                passed = True
                                detail = ""
                                if rule_type == "ROW_COUNT":
                                    n = float(scalar(f"select count(*) from {table_name}"))
                                    lo, hi = config.get("min"), config.get("max")
                                    passed = (lo is None or n >= lo) and (hi is None or n <= hi)
                                    detail = f"row_count={int(n)}, min={lo}, max={hi}"
                                elif rule_type == "NULL_RATE":
                                    total = float(scalar(f"select count(*) from {table_name}"))
                                    nulls = float(scalar(
                                        f"select count(*) from {table_name} where {column_name} is null"))
                                    rate = 0.0 if total == 0 else nulls / total
                                    max_rate = float(config.get("max", 0.0))
                                    passed = rate <= max_rate
                                    detail = f"null_rate={rate}, max={max_rate}"
                                elif rule_type == "UNIQUE":
                                    # count(col) 不计 NULL；count(*) 会把 NULL 当重复，
                                    # 与页面手动执行（Java 侧）口径不一致。
                                    dup = float(scalar(
                                        f"select count({column_name}) - count(distinct {column_name}) "
                                        f"from {table_name}"))
                                    max_dup = int(config.get("max", 0))
                                    passed = dup <= max_dup
                                    detail = f"duplicates={int(dup)}, max={max_dup}"
                                elif rule_type == "RANGE":
                                    lo = config.get("min")
                                    hi = config.get("max")
                                    if lo is None and hi is None:
                                        raise RuntimeError("RANGE rule needs min or max")
                                    conditions = []
                                    if lo is not None:
                                        conditions.append(f"{column_name} < {float(lo)}")
                                    if hi is not None:
                                        conditions.append(f"{column_name} > {float(hi)}")
                                    bad = float(scalar(
                                        f"select count(*) from {table_name} "
                                        f"where " + " or ".join(conditions)))
                                    passed = bad == 0
                                    detail = f"out_of_range={int(bad)}"
                                elif rule_type == "FRESHNESS":
                                    # 规则配置里 dateColumn 可覆盖 column_name；统计业务日期当天的行数
                                    date_column = config.get("dateColumn") or column_name
                                    if not date_column or not re.fullmatch(
                                            r"[A-Za-z_][A-Za-z0-9_]*", date_column):
                                        raise RuntimeError("invalid date column")
                                    fresh = float(scalar(
                                        f"select count(*) from {table_name} "
                                        f"where {date_column} = '{biz_date}'"))
                                    minimum = float(config.get("min", 1))
                                    passed = fresh >= minimum
                                    detail = f"fresh_rows={int(fresh)}, min={int(minimum)}"
                                elif rule_type == "CUSTOM_SQL":
                                    # 两种存法都支持：sql_b64（UI 默认）与明文 config.sql
                                    raw_sql = config.get("sql_b64")
                                    sql = (base64.b64decode(raw_sql).decode("utf-8")
                                           if raw_sql else config.get("sql", ""))
                                    if not sql:
                                        raise RuntimeError("CUSTOM_SQL missing sql/sql_b64")
                                    val = scalar(_guard_readonly(sql.replace("${biz_date}", biz_date)))
                                    expected = config.get("expect", 1)
                                    passed = float(val) == float(expected)
                                    detail = f"value={val}, expect={expected}"
                                elif rule_type == "VOLATILITY":
                                    # TC7-G1：与 Java 侧 evaluate 同一口径——基线取本规则在
                                    # biz_date-N 天最近一次执行明细的 row_count；缺基线不判定。
                                    from datetime import date as _bd, timedelta as _td
                                    n = float(scalar(f"select count(*) from {table_name}"))
                                    windows = [int(w) for w in (config.get("windows") or []) if int(w) > 0]
                                    if not windows:
                                        raise RuntimeError("VOLATILITY rule needs windows")
                                    max_rate = config.get("maxChangeRate")
                                    if max_rate is None:
                                        raise RuntimeError("VOLATILITY rule needs maxChangeRate")
                                    max_rate = float(max_rate)
                                    day0 = _bd.fromisoformat(str(biz_date)[:10])
                                    parts = []
                                    compared = False
                                    for w in windows:
                                        cur.execute(
                                            "select detail from platform.quality_result where rule_id=%s"
                                            " and biz_date=%s order by id desc limit 1",
                                            (rule_id, day0 - _td(days=w)))
                                        hit = cur.fetchone()
                                        m = re.search("row_count=([0-9]+)", (hit[0] or "")) if hit else None
                                        if m is None:
                                            parts.append(f"{w}d=基线缺失")
                                            continue
                                        b = float(m.group(1))
                                        compared = True
                                        if b == 0 and n > 0:
                                            parts.append(f"{w}d=0→{int(n)} 超限")
                                            passed = False
                                            continue
                                        rate = 0.0 if b == 0 else (n - b) / b
                                        ok = abs(rate) <= max_rate
                                        passed = passed and ok
                                        parts.append(f"{w}d={rate * 100:+.1f}% {'达标' if ok else '超限'}")
                                    detail = (f"row_count={int(n)}, " + "; ".join(parts)
                                              + f", maxChangeRate={max_rate}"
                                              + ("" if compared else "（各窗口均缺基线，首轮不判定）"))
                                elif rule_type == "REGEX":
                                    # 不匹配行数 ≤ maxBad；NULL 不计入。方言：PG 用 !~，Doris/MySQL 用 regexp
                                    if not column_name:
                                        raise RuntimeError("REGEX rule needs column")
                                    pattern = str(config.get("pattern") or "")
                                    if not pattern:
                                        raise RuntimeError("REGEX rule needs pattern")
                                    esc = pattern.replace("'", "''")
                                    if ds_conn is not None:
                                        _nm, _t2, _url, _un, _pw = _datasource(datasource_id)
                                        pg = (_t2 or "").upper().startswith("POSTGRE")
                                    else:
                                        pg = datasource == "PG"
                                    if pg:
                                        cond = f"{column_name} !~ '{esc}'"
                                    else:
                                        cond = f"not ({column_name} regexp '{esc}')"
                                    bad = float(scalar(
                                        f"select count(*) from {table_name} "
                                        f"where {column_name} is not null and {cond}"))
                                    max_bad = int(config.get("maxBad", 0))
                                    passed = bad <= max_bad
                                    detail = f"regex_bad={int(bad)}, maxBad={max_bad}"
                                elif rule_type == "ENUM":
                                    # 不在白名单的行数 ≤ maxBad；NULL 不计入（口径同 UNIQUE）
                                    if not column_name:
                                        raise RuntimeError("ENUM rule needs column")
                                    allowed = config.get("allowed") or []
                                    if not allowed:
                                        raise RuntimeError("ENUM rule needs allowed")
                                    in_list = ", ".join(
                                        "'" + str(v).replace("'", "''") + "'" for v in allowed)
                                    bad = float(scalar(
                                        f"select count(*) from {table_name} "
                                        f"where {column_name} is not null and {column_name} not in ({in_list})"))
                                    max_bad = int(config.get("maxBad", 0))
                                    passed = bad <= max_bad
                                    detail = f"enum_bad={int(bad)}, maxBad={max_bad}"
                                elif rule_type == "DISCRETE":
                                    lo, hi = config.get("min"), config.get("max")
                                    if lo is None and hi is None:
                                        raise RuntimeError("DISCRETE rule needs min or max")
                                    d = float(scalar(
                                        f"select count(distinct {column_name}) from {table_name}"))
                                    passed = (lo is None or d >= float(lo)) and (hi is None or d <= float(hi))
                                    detail = f"distinct_count={int(d)}, min={lo}, max={hi}"
                                else:
                                    raise RuntimeError(f"unsupported rule_type: {rule_type}")
                                cur.execute(
                                    "insert into platform.quality_result (rule_id, biz_date, passed, detail) "
                                    "values (%s, %s, %s, %s)", (rule_id, biz_date, passed, detail))
                                # Commit the quality result before raising, otherwise the
                                # surrounding transaction rolls the audit row back.
                                conn.commit()
                                print(f"quality gate {rule_code} [{datasource}]: passed={passed} {detail}")
                                if not passed:
                                    raise RuntimeError(f"quality gate failed: {rule_code} {detail}")
                    finally:
                        if ds_conn is not None:
                            try:
                                ds_conn.close()
                            except Exception:
                                pass
                        try:
                            conn.close()
                        except Exception:
                            pass

                """);

        for (String code : order) {
            JsonNode task = taskByCode.get(code);
            String type = task.path("type").asText("SQL").toUpperCase(Locale.ROOT);
            String script = task.path("script").asText("");
            String ruleCode = task.path("ruleCode").asText("");
            // 数据开发默认跑项目绑定的 Doris 数仓；要连别的库必须显式绑定数据源 id。
            //
            // S1（2026-10-26 泳道 3 扫描 P0）：以前这里允许 "PG"，语义是「用 worker 的
            // DW_DB_* 连平台元数据库」，等于任何能发布工作流的人都能在平台库（含
            // platform.audit_log）上执行任意 SQL。PG 这类保留字一律拒绝；
            // 渲染出的 _connect() 仍保留，只给质量闸门写 platform.quality_result 用。
            String datasource = task.path("datasource").asText("DORIS")
                    .trim().toUpperCase(Locale.ROOT);
            Long datasourceId = task.hasNonNull("datasourceId") && task.get("datasourceId").asLong(0) > 0
                    ? task.get("datasourceId").asLong() : null;
            String reserved = PlatformInternalDb.reservedAliasReason(code, datasource);
            if (reserved != null && "SQL".equals(type)) {
                throw ApiException.badRequest(reserved);
            }
            if (datasourceId == null && !"DORIS".equals(datasource)) {
                throw ApiException.badRequest("任务 " + code
                        + " 的数据源只能是 DORIS，或绑定一个数据源 id: " + datasource);
            }
            String b64 = Base64.getEncoder().encodeToString(script.getBytes(StandardCharsets.UTF_8));
            int retries = Math.max(0, Math.min(5, task.path("retries").asInt(0)));
            // D1：只给 retries 不给间隔时，Prefect 默认 0 秒——三次重试背靠背，
            // 对锁冲突/网络抖动这类瞬时故障等于没有，所以这里必须一起下传。
            int retryDelayS = Math.max(0, Math.min(3600, task.path("retryDelayS").asInt(60)));
            py.append("@task(name=").append(pyStr(code))
                    .append(", retries=").append(retries)
                    .append(", retry_delay_seconds=").append(retryDelayS).append(")\n");
            py.append("def t_").append(code).append("(biz_date: str):\n");
            switch (type) {
                case "SHELL" -> py.append("    _run_shell(").append(pyStr(b64)).append(", biz_date)\n");
                case "PYTHON" -> py.append("    _run_python(").append(pyStr(b64)).append(", biz_date)\n");
                case "QUALITY_GATE" -> py.append("    _run_quality_gate(")
                        .append(pyStr(ruleCode)).append(", biz_date)\n");
                default -> py.append("    _run_sql(").append(pyStr(b64))
                        .append(", biz_date, ").append(pyStr(datasource))
                        .append(", ").append(datasourceId == null ? "None" : datasourceId.toString())
                        .append(", ").append(pyStr(code))
                        .append(", ").append(pyStr(task.path("database").asText("")))
                        .append(")\n");
            }
            py.append("\n");
        }

        py.append("@flow(name=FLOW_NAME, description=")
                .append(pyStr(workflowName + " (" + env + ")"))
                .append(")\n");
        py.append("def ").append(functionName).append("(biz_date: str = \"\"):\n");
        py.append("    \"\"\"Generated workflow. Manual triggers pass biz_date; scheduled runs derive it.\"\"\"\n");
        // 调度由 Prefect 直接创建 run，不会带参数；以前默认 "1970-01-01"，
        // 导致所有定时任务的 ${biz_date} 都是 1970-01-01。
        py.append("    if not biz_date or biz_date == \"1970-01-01\":\n");
        py.append("        from datetime import datetime as _dt\n");
        py.append("        from zoneinfo import ZoneInfo as _Zone\n");
        py.append("        try:\n");
        py.append("            from prefect.runtime import flow_run as _fr\n");
        py.append("            _start = _fr.scheduled_start_time\n");
        py.append("        except Exception:\n");
        py.append("            _start = None\n");
        py.append("        _start = _start or _dt.now(_Zone(\"Asia/Shanghai\"))\n");
        py.append("        if _start.tzinfo is None:\n");
        py.append("            _start = _start.replace(tzinfo=_Zone(\"UTC\"))\n");
        py.append("        biz_date = _start.astimezone(_Zone(\"Asia/Shanghai\")).strftime(\"%Y-%m-%d\")\n");
        // TC7-G2：先确认上游强规则，再提交任何任务。阻断查询失败（后端抖动）只告警，
        // 不把全部调度停掉——与运行期血缘上报同一个失败口径。
        py.append("    try:\n");
        py.append("        _check_quality_blocks(biz_date)\n");
        py.append("    except RuntimeError:\n");
        py.append("        raise\n");
        py.append("    except Exception as _block_err:\n");
        py.append("        _log(f\"quality block check skipped: {_block_err}\")\n");
        Map<String, String> futureVars = new LinkedHashMap<>();
        for (String code : order) {
            futureVars.put(code, "f_" + code);
        }
        for (String code : order) {
            String var = futureVars.get(code);
            List<String> incoming = deps.get(code);
            // Resolve upstream futures first: a failed upstream must block downstream.
            for (String dep : incoming) {
                py.append("    ").append(futureVars.get(dep)).append(".result()\n");
            }
            py.append("    ").append(var).append(" = t_").append(code).append(".submit(biz_date");
            if (!incoming.isEmpty()) {
                py.append(", wait_for=[");
                for (int i = 0; i < incoming.size(); i++) {
                    if (i > 0) {
                        py.append(", ");
                    }
                    py.append(futureVars.get(incoming.get(i)));
                }
                py.append("]");
            }
            py.append(")\n");
        }
        // Resolve every future so a failed leaf task also fails the flow.
        py.append("\n    for _future in [");
        int idx = 0;
        for (String code : order) {
            if (idx++ > 0) {
                py.append(", ");
            }
            py.append(futureVars.get(code));
        }
        py.append("]:\n        _future.result()\n");

        return new RenderedFlow(flowName, functionName, filename, entrypoint, py.toString());
    }

    public String flowName(String projectCode, String env, String workflowCode) {
        String raw = "p_" + projectCode + "_" + env + "_" + workflowCode;
        return raw.toLowerCase(Locale.ROOT).replaceAll("[^a-z0-9_]", "_");
    }

    private List<String> topologicalOrder(Collection<String> codes, Map<String, List<String>> next,
                                          Map<String, Integer> indegree) {
        Map<String, Integer> degree = new LinkedHashMap<>(indegree);
        Deque<String> queue = new ArrayDeque<>();
        degree.forEach((k, v) -> {
            if (v == 0) {
                queue.add(k);
            }
        });
        List<String> order = new ArrayList<>();
        while (!queue.isEmpty()) {
            String cur = queue.poll();
            order.add(cur);
            for (String nx : next.getOrDefault(cur, List.of())) {
                int d = degree.merge(nx, -1, Integer::sum);
                if (d == 0) {
                    queue.add(nx);
                }
            }
        }
        if (order.size() != codes.size()) {
            throw ApiException.badRequest("工作流依赖存在环，无法发布");
        }
        return order;
    }

    private String pyStr(String value) {
        if (value == null) {
            return "None";
        }
        return "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"")
                .replace("\r", "\\r").replace("\n", "\\n") + "\"";
    }

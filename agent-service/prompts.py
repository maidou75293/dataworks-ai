def route_modules(message: str) -> list[str]:
    text = (message or "").lower()
    hits = [m for m, words in KEYWORDS.items() if any(w in text for w in words)]
    # 没命中任何模块时只加载总则，避免把全部模块塞进上下文
    return hits


def system_prompt(message: str) -> str:
    parts = [GENERAL_PROMPT, OPERATION_POLICY]
    modules = route_modules(message)
    for module in modules:
        parts.append(MODULE_PROMPTS[module])
    # 流程 SOP 中间层：命中模块带出对应 playbook（REQ-AGENT-SOP-PLAYBOOK-1）。
    # 懒导入避免模块环；加载器按目录签名重读=改 playbooks/ 文件即生效。
    import playbook
    sop = playbook.render_for_modules(modules)
    if sop:
        parts.append(sop)
    return "\n\n".join(parts)
